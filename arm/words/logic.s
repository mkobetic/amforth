@ -----------------------------------------------------------------------------
  CODEWORD  "and", AND /* ( x1 x2 -- x3 ) x3 = x1 & x2 */
@ -----------------------------------------------------------------------------
  popnos r0
  ands TOS, r0
  NEXT
END AND

@ -----------------------------------------------------------------------------
  CODEWORD  "or", OR /* ( x1 x2 -- x3 ) x3 = x1 | x2 */
@ -----------------------------------------------------------------------------
  popnos r0
  orrs TOS, r0
  NEXT
END OR

@ -----------------------------------------------------------------------------
  COLON  "not", NOT /* ( f1 -- f2 )  f = ~f (logical not) */
@ -----------------------------------------------------------------------------
  .word XT_ZEROEQUAL
  .word XT_EXIT 
END NOT

@ -----------------------------------------------------------------------------
  CODEWORD  "rshift", RSHIFT /* ( x1 u -- x2 ) x2 = x1 >> u */
@ -----------------------------------------------------------------------------
  popnos r0
  lsrs r0, TOS
  movs TOS, r0
  NEXT
END RSHIFT

@ -----------------------------------------------------------------------------
  CODEWORD  "lshift", LSHIFT /* ( x1 u -- x2 ) x2 = x1 << u */
@ -----------------------------------------------------------------------------
  popnos r0
  lsls r0, TOS
  movs TOS, r0
  NEXT
END LSHIFT
