@ -----------------------------------------------------------------------------
  CODEWORD  "and", AND /* ( x1 x2 -- x3 ) x3 = x1 & x2 */
@ -----------------------------------------------------------------------------
  ldm psp!, {r0}
  ands tos, r0
  NEXT
END AND

@ -----------------------------------------------------------------------------
  CODEWORD  "or", OR /* ( x1 x2 -- x3 ) x3 = x1 | x2 */
@ -----------------------------------------------------------------------------
  ldm psp!, {r0}
  orrs tos, r0
  NEXT
END OR

@ -----------------------------------------------------------------------------
  CODEWORD  "not", NOT /* ( x1 -- x2 ) x2 = ~x1 */
@ -----------------------------------------------------------------------------
  mvns tos, tos
  NEXT
END NOT

@ -----------------------------------------------------------------------------
  CODEWORD  "rshift", RSHIFT /* ( x1 u -- x2 ) x2 = x1 >> u */
@ -----------------------------------------------------------------------------
  ldm psp!, {r0}
  lsrs r0, tos
  movs tos, r0
  NEXT
END RSHIFT

@ -----------------------------------------------------------------------------
  CODEWORD  "lshift", LSHIFT /* ( x1 u -- x2 ) x2 = x1 << u */
@ -----------------------------------------------------------------------------
  ldm psp!, {r0}
  lsls r0, tos
  movs tos, r0
  NEXT
END LSHIFT
