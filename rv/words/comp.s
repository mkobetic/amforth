# Comparision operators

# -----------------------------------------------------------------------------
  CODEWORD "0=",ZEROEQUAL /* ( n -- f ) f = n == 0 */
# -----------------------------------------------------------------------------
  sltiu s3, s3, 1
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END ZEROEQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "0<>", NOTZEROEQUAL /* ( n -- f ) f = n != 0 */
# -----------------------------------------------------------------------------
  sltiu s3, s3, 1
  addi s3, s3, -1
  NEXT
END NOTZEROEQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "0<", ZEROLESS /* ( n -- f ) f = n < 0 */
# -----------------------------------------------------------------------------
  srai s3, s3, 31
  NEXT
END ZEROLESS

# -----------------------------------------------------------------------------
  CODEWORD  ">=", GREATEREQUAL /* ( n1 n2 -- f ) f = n1 >= n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  slt s3, t0, s3
  addi s3, s3, -1
  NEXT
END GREATEREQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "<=", LESSEQUAL /* ( n1 n2 -- f ) f = n1 <= n2 */       
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  slt s3, s3, t0
  addi s3, s3, -1
  NEXT
END LESSEQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "<", LESS /* ( n1 n2 -- f ) f = n1 < n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  slt s3, t0, s3
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END LESS

# -----------------------------------------------------------------------------
  CODEWORD  ">", GREATER /* ( n1 n2 -- f ) f = n1 > n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  slt s3, s3, t0
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END GREATER

# -----------------------------------------------------------------------------
  CODEWORD  "u>=", UGREATEREQUAL /* ( u1 u2 -- f ) f = u1 >= u2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  sltu s3, t0, s3
  addi s3, s3, -1
  NEXT
END UGREATEREQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "u<=", ULESSEQUAL /* ( u1 u2 -- f ) f = u1 <= u2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  sltu s3, s3, t0
  addi s3, s3, -1
  NEXT
END ULESSEQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "u<", ULESS /* ( u1 u2 -- f ) f = u1 < u2 */ 
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  sltu s3, t0, s3
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END ULESS

# -----------------------------------------------------------------------------
  CODEWORD  "u>", UGREATER /* ( u1 u2 -- f ) f = u1 > u2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  sltu s3, s3, t0
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END UGREATER

# -----------------------------------------------------------------------------
  CODEWORD  "<>", NOTEQUAL /* ( n1 n2 -- f ) f = n1 != n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  xor s3, s3, t0
  sltiu s3, s3, 1
  addi s3, s3, -1
  NEXT
END NOTEQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "=", EQUAL /* ( n1 n2 -- f ) f = n1 == n2 */
# -----------------------------------------------------------------------------
equal_einsprung:
  lw t0, 0(s4)
  addi s4, s4, 4
  xor s3, s3, t0
  sltiu s3, s3, 1
  addi s3, s3, -1
  xori s3, s3, -1
  NEXT
END EQUAL

# -----------------------------------------------------------------------------
  CODEWORD  "min", MIN /* ( n1 n2 -- n3 ) n3 = min(n1, n2) */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  blt s3, t0, 1f
    mv s3, t0
1:
  NEXT
END MIN

# -----------------------------------------------------------------------------
  CODEWORD  "max", MAX /* ( n1 n2 -- n3 ) n3 = max(n1, n2) */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  blt t0, s3, 1f
    mv s3, t0
1:NEXT
END MAX

# -----------------------------------------------------------------------------
  CODEWORD  "umin", UMIN /* ( u1 u2 -- u3 ) u3 = min(u1, u2) */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  bltu s3, t0, 1f
    mv s3, t0
1:NEXT
END UMIN

# -----------------------------------------------------------------------------
  CODEWORD  "umax", UMAX /* ( u1 u2 -- u3 ) u3 = max(u1, u2) */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  bltu t0, s3, 1f
    mv s3, t0
1:NEXT
END UMAX
