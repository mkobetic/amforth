# -----------------------------------------------------------------------------
#  Multiplication, Division and Remainder available as opcodes in RV32IM
#  Rewrite these to get a pure RV32I Forth.
# -----------------------------------------------------------------------------

# -----------------------------------------------------------------------------
  CODEWORD  "m*", MSTAR /* ( n1 n2 -- d ) d = n1*n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  mul t1, t0, s3
  sw t1, 0(s4)
  mulh s3, t0, s3
  NEXT
END MSTAR

# -----------------------------------------------------------------------------
  CODEWORD  "/", SLASH /* ( n1 n2 -- n3 ) n3 is quotient of n1 / n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  div s3, t0, s3
  NEXT
END SLASH

# -----------------------------------------------------------------------------
  CODEWORD  "mod", MOD /* ( n1 n2 -- n3 n4 ) n3 is remainder and n4 the quotient of n1 / n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  addi s4, s4, 4
  rem s3, t0, s3
  NEXT
END MOD

# -----------------------------------------------------------------------------
  CODEWORD  "u/mod", USLASHMOD /* ( u1 u2 -- u3 u4 ) u3 is remainder and u4 the quotient of u1 / u2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  remu t1, t0, s3
  sw t1, 0(s4)
  divu s3, t0, s3
  NEXT
END USLASHMOD

# -----------------------------------------------------------------------------
  CODEWORD  "/mod", SLASHMOD /* ( n1 n2 -- n3 n4 ) n3 is remainder and n4 the quotient of n1 / n2 */
# -----------------------------------------------------------------------------
  lw t0, 0(s4)
  rem t1, t0, s3
  sw t1, 0(s4)
  div s3, t0, s3
  NEXT
END SLASHMOD
